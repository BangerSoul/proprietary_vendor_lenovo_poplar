set -e

DEVICE=poplar
VENDOR=lenovo

# Determine script and root directories
MY_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
ANDROID_ROOT="$(cd "${MY_DIR}/../../.." 2>/dev/null && pwd || echo "")"
HELPER="${ANDROID_ROOT}/tools/extract-utils/extract_utils.sh"

# Mode A: LineageOS extract_utils is available
if [ -n "${ANDROID_ROOT}" ] && [ -f "${HELPER}" ]; then
    source "${HELPER}"

    # Initialize helper
    setup_vendor "${DEVICE}" "${VENDOR}" "${ANDROID_ROOT}"

    # Write makefile headers
    write_headers

    # Process blobs list
    write_makefiles "${MY_DIR}/proprietary-files.txt"

    # Finalize
    write_footers
    exit 0
fi

# Mode B: Standalone Fallback Generator
echo "Notice: Standard extract_utils.sh not found at ${HELPER}."
echo "Activating standalone fallback makefile generator for ${VENDOR}/${DEVICE}..."

PRODUCTMK="${MY_DIR}/${DEVICE}-vendor.mk"
ANDROIDMK="${MY_DIR}/Android.mk"
BOARDMK="${MY_DIR}/BoardConfigVendor.mk"
PROPLIST="${MY_DIR}/proprietary-files.txt"

# 1. Generate Android.mk
cat <<EOF >"${ANDROIDMK}"
# Automatically generated file. DO NOT MODIFY
#
# This file is generated by device/${VENDOR}/${DEVICE}/setup-makefiles.sh

LOCAL_PATH := \$(call my-dir)

ifeq (\$(TARGET_DEVICE),${DEVICE})

endif
EOF

# 2. Generate BoardConfigVendor.mk
cat <<EOF >"${BOARDMK}"
# Automatically generated file. DO NOT MODIFY
#
# This file is generated by device/${VENDOR}/${DEVICE}/setup-makefiles.sh

# Vendor Image Filesystem Type
BOARD_VENDORIMAGE_FILE_SYSTEM_TYPE := erofs

# MediaTek Sepolicy Integration
BOARD_VENDOR_SEPOLICY_DIRS += \\
    vendor/${VENDOR}/${DEVICE}/sepolicy/vendor
EOF

# 3. Generate poplar-vendor.mk
cat <<EOF >"${PRODUCTMK}"
# Automatically generated file. DO NOT MODIFY
#
# This file is generated by device/${VENDOR}/${DEVICE}/setup-makefiles.sh

PRODUCT_SOONG_NAMESPACES += \\
    vendor/${VENDOR}/${DEVICE}

EOF

if [ -f "${PROPLIST}" ]; then
    # Temporary arrays
    declare -a COPY_ENTRIES
    declare -a PKG_ENTRIES

    while IFS= read -r line || [ -n "$line" ]; do
        # Trim leading and trailing whitespace using pure bash builtins
        line="${line#"${line%%[![:space:]]*}"}"
        line="${line%"${line##*[![:space:]]}"}"
        [ -z "$line" ] && continue
        [[ "$line" =~ ^# ]] && continue

        # Strip pinned SHA1 hash if present
        line="${line%%|*}"

        # Check if line indicates package module (starts with -)
        IS_PKG=false
        if [[ "$line" =~ ^- ]]; then
            IS_PKG=true
            line="${line#-}"
        fi

        # Extract MODULE argument if specified
        MOD_OVERRIDE=""
        REGEX=';MODULE=([^;]+)'
        if [[ "$line" =~ $REGEX ]]; then
            MOD_OVERRIDE="${BASH_REMATCH[1]}"
        fi

        # Strip semicolon arguments
        line="${line%%;*}"

        # Separate src:dst if specified
        if [[ "$line" =~ : ]]; then
            SRC_FILE="${line%%:*}"
            DST_FILE="${line##*:}"
        else
            SRC_FILE="$line"
            DST_FILE="$line"
        fi

        # Detect package by extension (.apk, .jar, .apex)
        if [[ "$SRC_FILE" =~ \.(apk|jar|apex)$ ]]; then
            IS_PKG=true
        fi

        if [ "$IS_PKG" = true ]; then
            if [ -n "$MOD_OVERRIDE" ]; then
                MOD_NAME="$MOD_OVERRIDE"
            else
                MOD_NAME="$(basename "${DST_FILE}")"
                if [[ "$MOD_NAME" =~ \.(so|apk|jar|apex)$ ]]; then
                    MOD_NAME="${MOD_NAME%.*}"
                fi
            fi
            # Add to PKG_ENTRIES if not already present
            ALREADY_EXISTS=false
            for existing in "${PKG_ENTRIES[@]}"; do
                if [ "$existing" = "$MOD_NAME" ]; then
                    ALREADY_EXISTS=true
                    break
                fi
            done
            if [ "$ALREADY_EXISTS" = false ]; then
                PKG_ENTRIES+=("$MOD_NAME")
            fi
        else
            # Determine target partition macro
            PART_MACRO="TARGET_COPY_OUT_VENDOR"
            REL_TARGET="${DST_FILE}"
            if [[ "$DST_FILE" =~ ^vendor/ ]]; then
                PART_MACRO="TARGET_COPY_OUT_VENDOR"
                REL_TARGET="${DST_FILE#vendor/}"
            elif [[ "$DST_FILE" =~ ^vendor_dlkm/ ]]; then
                PART_MACRO="TARGET_COPY_OUT_VENDOR_DLKM"
                REL_TARGET="${DST_FILE#vendor_dlkm/}"
            elif [[ "$DST_FILE" =~ ^odm/ ]]; then
                PART_MACRO="TARGET_COPY_OUT_ODM"
                REL_TARGET="${DST_FILE#odm/}"
            elif [[ "$DST_FILE" =~ ^product/ ]]; then
                PART_MACRO="TARGET_COPY_OUT_PRODUCT"
                REL_TARGET="${DST_FILE#product/}"
            elif [[ "$DST_FILE" =~ ^system_ext/ ]]; then
                PART_MACRO="TARGET_COPY_OUT_SYSTEM_EXT"
                REL_TARGET="${DST_FILE#system_ext/}"
            fi

            COPY_ENTRIES+=("vendor/${VENDOR}/${DEVICE}/proprietary/${DST_FILE}:\$(${PART_MACRO})/${REL_TARGET}")
        fi
    done <"${PROPLIST}"

    # Write PRODUCT_COPY_FILES
    COUNT=${#COPY_ENTRIES[@]}
    if [ ${COUNT} -gt 0 ]; then
        echo "PRODUCT_COPY_FILES += \\" >>"${PRODUCTMK}"
        for ((i=0; i<COUNT; i++)); do
            if [ $i -lt $((COUNT - 1)) ]; then
                echo "    ${COPY_ENTRIES[$i]} \\" >>"${PRODUCTMK}"
            else
                echo "    ${COPY_ENTRIES[$i]}" >>"${PRODUCTMK}"
            fi
        done
    fi

    # Write PRODUCT_PACKAGES if any
    PKG_COUNT=${#PKG_ENTRIES[@]}
    if [ ${PKG_COUNT} -gt 0 ]; then
        echo "" >>"${PRODUCTMK}"
        echo "PRODUCT_PACKAGES += \\" >>"${PRODUCTMK}"
        for ((i=0; i<PKG_COUNT; i++)); do
            if [ $i -lt $((PKG_COUNT - 1)) ]; then
                echo "    ${PKG_ENTRIES[$i]} \\" >>"${PRODUCTMK}"
            else
                echo "    ${PKG_ENTRIES[$i]}" >>"${PRODUCTMK}"
            fi
        done
    fi
fi

echo "Successfully generated ${DEVICE}-vendor.mk, Android.mk, and BoardConfigVendor.mk"
